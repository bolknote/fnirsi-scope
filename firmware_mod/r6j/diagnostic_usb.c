static void dzero(u8 *p,u32 n){for(u32 i=0;i<n;i++)p[i]=0;}
static void dcopy(u8 *d,const u8 *s,u32 n){
 /* RAM.BIN can cover the USB buffer itself. Respect overlap. */
 if((u32)d>(u32)s && (u32)d-(u32)s<n){while(n){--n;d[n]=s[n];}}
 else for(u32 i=0;i<n;i++)d[i]=s[i];
}
static void dle16(u8 *p,u32 n){p[0]=(u8)n;p[1]=(u8)(n>>8);}
